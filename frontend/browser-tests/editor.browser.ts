import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('http://127.0.0.1:1420/browser-tests/editor-harness.html')
  await expect(page.getByRole('textbox', { name: '카드 템플릿 코드' })).toBeVisible({ timeout: 15000 })
})

test('highlights Anki references and supports find, replace, undo, redo and wrapping', async ({ page }, testInfo) => {
  const editor = page.getByRole('textbox', { name: '카드 템플릿 코드' })
  await expect(editor.locator('.cm-anki-field')).toHaveText('{{Front}}')
  await expect(editor.locator('.cm-anki-media')).toHaveText('photo.png')
  await expect(page.locator('.cm-lineNumbers')).toContainText('4')
  await editor.click()
  await page.keyboard.press('Control+f')
  await page.getByRole('textbox', { name: '찾을 내용', exact: true }).fill('card')
  await page.getByRole('textbox', { name: '바꿀 내용', exact: true }).fill('flashcard')
  await page.getByRole('button', { name: '모두 바꾸기', exact: true }).click()
  await expect(editor).toContainText('class="flashcard"')
  await page.getByRole('button', { name: '찾기 닫기', exact: true }).click()
  await page.getByRole('button', { name: '입력 실행 취소', exact: true }).click()
  await expect(editor).toContainText('class="card"')
  await page.getByRole('button', { name: '다시 실행', exact: true }).click()
  await expect(editor).toContainText('class="flashcard"')
  const wrapping = page.getByRole('button', { name: '자동 줄바꿈' })
  await wrapping.click()
  await expect(wrapping).toHaveAttribute('aria-pressed', 'false')
  await expect(editor).not.toHaveClass(/cm-lineWrapping/)
  await wrapping.click()
  await expect(editor).toHaveClass(/cm-lineWrapping/)
  await page.screenshot({ path: testInfo.outputPath('card-editor.png') })
})

test('indents with Tab, unindents with Shift+Tab and lets Escape then Tab leave the editor', async ({ page }) => {
  const editor = page.getByRole('textbox', { name: '카드 템플릿 코드' })
  await editor.click()
  await page.keyboard.press('Control+Home')
  await page.keyboard.press('Tab')
  await expect(editor.locator('.cm-line').first()).toHaveText('  <div class="card">')
  await page.keyboard.press('Shift+Tab')
  await expect(editor.locator('.cm-line').first()).toHaveText('<div class="card">')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Tab')
  await expect(editor).not.toBeFocused()
})

test('preserves HTML/CSS drafts across tabs, saves with Ctrl+S and discards without restoring stale undo', async ({ page }) => {
  const editor = page.getByRole('textbox', { name: '카드 템플릿 코드' })
  await editor.click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('한글 편집')
  await page.getByRole('button', { name: '공통 CSS' }).click()
  await editor.click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('\n.card { font-size: 24px; }')
  await page.keyboard.press('Control+s')
  await expect(page.getByTestId('saved-css')).toContainText('font-size: 24px')
  await expect(page.getByRole('status')).toHaveText('작업본에 저장됨')
  await page.getByRole('button', { name: '앞면 HTML' }).click()
  await expect(editor).toContainText('한글 편집')
  await editor.click()
  await page.keyboard.press('Control+s')
  await expect(page.getByTestId('saved-front')).toContainText('한글 편집')
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('임시 변경')
  await page.getByRole('button', { name: '되돌리기', exact: true }).click()
  await expect(editor).not.toContainText('임시 변경')
  await expect(editor).toContainText('한글 편집')
  await expect(page.getByRole('button', { name: '입력 실행 취소', exact: true })).toBeDisabled()
})

test('completes Korean fields and conditional tags without duplicating existing braces', async ({ page }, testInfo) => {
  const editor = page.getByRole('textbox', { name: '카드 템플릿 코드' })
  await editor.click()
  await page.keyboard.press('Control+a')
  await page.keyboard.type('{{')
  await expect(page.getByRole('option', { name: '발음Anki 필드', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('field-completion.png') })
  await page.keyboard.insertText('발')
  await expect(page.getByRole('option', { name: '발음Anki 필드', exact: true })).toBeVisible()
  // CodeMirror deliberately ignores acceptance keys for 75 ms after opening a list.
  await page.waitForTimeout(100)
  await page.keyboard.press('Enter')
  await expect(editor).toHaveText('{{발음}}')
  await page.keyboard.press('Control+a')
  await page.keyboard.type('{{#Fr')
  await page.getByRole('option', { name: 'FrontAnki 필드', exact: true }).click()
  await expect(editor).toHaveText('{{#Front}}')
  // Re-complete a partial name with the closing braces already present.
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('Backspace')
  await page.keyboard.press('Control+Space')
  await page.getByRole('option', { name: 'FrontAnki 필드', exact: true }).click()
  await expect(editor).toHaveText('{{#Front}}')
  await page.getByRole('button', { name: '뒷면 HTML' }).click()
  await editor.click()
  await page.keyboard.press('Control+End')
  await page.keyboard.type('{{FrontS')
  await page.getByRole('option', { name: 'FrontSide앞면 전체', exact: true }).click()
  await expect(editor).toContainText('{{Back}}{{FrontSide}}')
})

