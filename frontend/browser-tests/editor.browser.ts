test('inserts media at the retained cursor, restores focus and undoes insertion in one step', async ({ page }, testInfo) => {
  const editor = page.getByRole('textbox', { name: '카드 템플릿 코드' })
  await editor.click()
  await page.keyboard.press('Control+Home')
  await page.keyboard.insertText('before')
  await page.getByRole('button', { name: '미디어 삽입', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '미디어 삽입' })
  await dialog.getByRole('textbox', { name: '미디어 파일 검색' }).fill('photo')
  await dialog.getByRole('button', { name: '이미지 photo.png' }).click()
  await expect(dialog.getByLabel('삽입할 코드')).toHaveText('<img src="photo.png" alt="">')
  await page.screenshot({ path: testInfo.outputPath('media-insert.png') })
  await dialog.getByRole('button', { name: '삽입', exact: true }).click()
  await expect(editor).toBeFocused()
  await expect(editor).toContainText('before<img src="photo.png" alt=""><div')
  await page.keyboard.press('Control+z')
  await expect(editor).toContainText('before<div')
  await page.getByRole('button', { name: '미디어 삽입', exact: true }).click()
  await dialog.getByRole('button', { name: '음성 voice.mp3' }).click()
  await dialog.getByRole('button', { name: '삽입', exact: true }).click()
  await expect(editor).toContainText('before[sound:voice.mp3]<div')
  await page.keyboard.press('Control+s')
  await expect(page.getByTestId('saved-front')).toContainText('[sound:voice.mp3]')
})

test('offers CSS media snippets, replaces the selection, and leaves drafts unchanged on cancel', async ({ page }) => {
  await page.getByRole('button', { name: '공통 CSS' }).click()
  const editor = page.getByRole('textbox', { name: '카드 템플릿 코드' })
  await editor.click()
  await page.keyboard.press('Control+a')
  await page.getByRole('button', { name: '미디어 삽입', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '미디어 삽입' })
  await expect(dialog.getByRole('button', { name: '음성 voice.mp3' })).toHaveCount(0)
  await dialog.getByRole('button', { name: '이미지 photo.png' }).click()
  await expect(dialog.getByLabel('삽입할 코드')).toHaveText('background-image: url("photo.png");')
  await dialog.getByRole('button', { name: '폰트 _한글 폰트.woff2' }).click()
  await dialog.getByRole('button', { name: '삽입', exact: true }).click()
  await expect(editor).toContainText('@font-face')
  await expect(editor).not.toContainText('background: #172239')
  await page.getByRole('button', { name: '미디어 삽입', exact: true }).click()
  await dialog.getByRole('textbox', { name: '미디어 파일 검색' }).fill('no-such-file')
  await expect(dialog.getByText('검색 결과가 없습니다.')).toBeVisible()
  await expect(dialog.getByRole('button', { name: '삽입', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(editor).toContainText('@font-face')
})
